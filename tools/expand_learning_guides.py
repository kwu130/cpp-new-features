def main() -> None:
    changed = 0
    for path in sorted((ROOT / "docs").glob("cpp*/*.md")):
        if path.name == "README.md":
            continue
        text = path.read_text(encoding="utf-8")
        if START in text:
            prefix, remainder = text.split(START, 1)
            if END not in remainder:
                raise RuntimeError(f"missing generated end marker: {path}")
            _, suffix = remainder.split(END, 1)
            text = prefix.rstrip() + "\n" + suffix.lstrip("\n")
        appendix = build_appendix(path, text)
        path.write_text(text.rstrip() + "\n\n" + appendix, encoding="utf-8")
        changed += 1
    print(f"updated {changed} feature tutorials")


if __name__ == "__main__":
    main()
