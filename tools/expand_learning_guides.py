def category(path: Path, title: str) -> str:
    text = f"{path.name} {title}".lower()
    if any(word in text for word in ("thread", "concurrency", "atomic", "mutex", "synchronization", "jthread")):
        return "concurrency"
    if any(word in text for word in ("pointer", "move", "pmr", "view", "span")):
        return "ownership"
    if any(word in text for word in ("template", "concept", "fold", "deduction", "integer-sequence", "compile-time")):
        return "templates"
    if any(word in text for word in ("container", "range-for", "ranges")):
        return "containers"
    if any(word in text for word in ("filesystem", "format", "chrono", "charconv", "literals", "utilities", "string")):
        return "library"
    return "language"


def inline_terms(text: str) -> list[str]:
    terms: list[str] = []
    for value in re.findall(r"`([^`\n]+)`", text):
        value = value.strip()
        if not value or len(value) > 48 or value.startswith("<!--"):
            continue
        if value not in terms:
            terms.append(value)
    return terms[:18]


def term_description(term: str) -> str:
    if term.startswith("std::"):
        return "标准命名空间中的类型、函数或对象；需要核对引入版本、头文件、重载和复杂度。"
    if "(" in term or term.endswith("()"):
        return "可调用语法或成员操作；分析参数传递、返回值、异常与前置条件。"
    if term.startswith("operator") or any(symbol in term for symbol in ("<=>", "&&", "||")):
        return "语言运算或重载入口；需要关注优先级、求值顺序和重写规则。"
    if term in {"auto", "decltype", "constexpr", "consteval", "constinit", "noexcept"}:
        return "编译期语言说明符；影响类型推导、常量求值或异常契约。"
    return "本专题核心术语；结合上下文确认它表示类型、表达式、状态还是接口契约。"


